import { expect, test } from "@playwright/test";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { inventory, seedStore, storedPath, tamperOneByte } from "./helpers/m1-seed";
import { receiptDigest } from "../lib/m1/format";

const sha = (bytes: Buffer) => createHash("sha256").update(bytes).digest("hex");

test("real evidence refusal keeps its bytes and renders its real audit, export recovery keeps the baseline", async ({ page }) => {
  test.skip(process.platform !== "linux", "Acceptance runs on the Linux CI runner.");
  const seeded = await seedStore(page.request, { exports: 1, complete: true });
  expect((await page.request.post("/api/oscal/validate", { data: { scenario: "current" } })).ok()).toBeTruthy();
  const baselineResponse = await page.request.post("/api/baseline");
  expect(baselineResponse.ok(), await baselineResponse.text()).toBeTruthy();
  const baseline = (await baselineResponse.json()).packageState.pipeline.baseline;
  const exported = await page.request.post("/api/oscal/export");
  expect(exported.ok(), await exported.text()).toBeTruthy();
  const evidence = seeded.objects.find(item => item.kind === "evidence")!;
  const metadata = (await inventory(page.request)).objects.find(item => item.objectKey === evidence.objectKey)! as typeof evidence & { controlId: string; evidenceId: string };
  const changed = tamperOneByte(evidence);
  const bytesRoute = `/api/controls/${metadata.controlId}/evidence/${metadata.evidenceId}/bytes`;
  const refused = await page.request.get(bytesRoute);
  expect(refused.status()).toBe(409);
  const details = (await refused.json()).error.details;
  expect(details.recordedDigest).toBe(sha(changed.before));
  expect(details.recomputedDigest).toBe(sha(changed.after));
  expect(details.objectKey).toBe(evidence.objectKey);
  expect(readFileSync(changed.file)).toEqual(changed.after);
  await page.goto(`/stored-evidence?objectKey=${evidence.objectKey}`);
  await expect(page.getByTestId("m1-frame22")).toHaveAttribute("data-state", "evidence-mismatch");
  await expect(page.getByTestId("m1-recorded")).toHaveText(receiptDigest(details.recordedDigest));
  await expect(page.getByTestId("m1-recomputed")).toHaveText(receiptDigest(details.recomputedDigest));
  await page.getByRole("link", { name: /Open audit trail/ }).click();
  await expect(page.getByTestId("m1-frame23")).toHaveAttribute("data-state", "evidence");
  const rows = page.getByTestId("m1-audit-row").filter({ hasText: "Read refused" });
  await expect(rows).toHaveCount(1);
  await expect(rows.first().getByTestId("m1-audit-by")).toHaveText("person not recorded");
  const trail = await page.request.get(`/api/digest/refusals/${evidence.objectKey}`);
  expect((await trail.json()).entries[0].refusedAt).toBe(details.refusedAt);
  expect(readFileSync(changed.file)).toEqual(changed.after);

  await page.goto("/verify-stored-files");
  await expect(page.getByTestId("m1-count-checked")).toHaveText("3");
  await expect(page.getByTestId("m1-count-match")).toHaveText("2");
  await expect(page.getByTestId("m1-count-mismatch")).toHaveText("1");
  await expect(page.getByTestId("m1-count-unreadable")).toHaveText("0");
  await expect(page.getByTestId("m1-link-refused")).toHaveAttribute("href", `/stored-evidence?objectKey=${evidence.objectKey}`);
  await page.locator(`[data-testid="m1-verify-row"][data-object="${evidence.objectKey}"]`).getByTestId("m1-link-regenerate").click();
  await expect(page.getByTestId("m1-frame24")).toHaveAttribute("data-state", "disabled");
  await expect(page.getByRole("button", { name: "Regenerate", exact: true })).toBeDisabled();
  writeFileSync(changed.file, changed.before);
  expect((await page.request.get(bytesRoute)).ok()).toBeTruthy();
  await page.goto(`/stored-evidence?objectKey=${evidence.objectKey}`);
  await expect(page.getByTestId("m1-frame22")).toHaveAttribute("data-state", "all-match");

  const files = await inventory(page.request);
  const oscal = files.objects.filter(item => item.role === "oscal").sort((a,b) => String(b.exportId).localeCompare(String(a.exportId)))[0]!;
  const old = tamperOneByte(oscal);
  expect((await page.request.get("/api/artifacts/oscal")).status()).toBe(409);
  await page.goto(`/stored-evidence?objectKey=${oscal.objectKey}`);
  await expect(page.getByTestId("m1-frame22")).toHaveAttribute("data-state", "export-mismatch");
  await page.getByTestId("m1-link-regenerate").click();
  await expect(page.getByTestId("m1-frame24")).toHaveAttribute("data-state", "confirm");
  await page.getByTestId("m1-regenerate").click();
  await expect(page.getByTestId("m1-frame24")).toHaveAttribute("data-state", "done");
  const versions = await inventory(page.request);
  const next = versions.objects.find(item => item.role === "oscal" && item.exportId === "exp-0003")!;
  expect(next).toBeTruthy();
  expect(versions.objects.some(item => item.objectKey === oscal.objectKey && item.exportId === "exp-0002")).toBe(true);
  const listed = page.getByTestId("m1-export-row");
  await expect(listed.nth(0)).toContainText("exp-0003");
  await expect(listed.nth(1)).toContainText("exp-0002");
  await expect(page.getByTestId("m1-validator")).toContainText("GREEN");
  expect(readFileSync(old.file)).toEqual(old.after);
  const current = (await (await page.request.get("/api/package")).json()).packageState;
  expect(current.pipeline.baseline).toMatchObject({ id: baseline.id, exportId: baseline.exportId });
  expect(sha(readFileSync(storedPath(next)))).toBe(next.recordedDigest);
  const countBefore = versions.objects.length;
  await page.goto("/verify-stored-files");
  await page.locator(`[data-testid="m1-verify-row"][data-object="${oscal.objectKey}"]`).getByTestId("m1-link-regenerate").click();
  await expect(page.getByTestId("m1-frame24")).toHaveAttribute("data-state", "disabled");
  await expect(page.getByTestId("m1-state-card")).toContainText("This stored version is kept for investigation.");
  await expect(page.getByTestId("m1-regenerate")).toBeDisabled();
  await page.goto("/verify-stored-files");
  await page.locator(`[data-testid="m1-verify-row"][data-object="${next.objectKey}"]`).getByTestId("m1-link-regenerate").click();
  await expect(page.getByTestId("m1-frame24")).toHaveAttribute("data-state", "confirm");
  await page.getByTestId("m1-regenerate").click();
  await expect(page.getByTestId("m1-frame24")).toHaveAttribute("data-state", "not-needed");
  expect((await inventory(page.request)).objects.length).toBe(countBefore);
});
