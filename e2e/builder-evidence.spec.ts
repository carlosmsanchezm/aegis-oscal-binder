import { navigateWorkspace } from "./helpers/navigation";
import { test, expect } from "@playwright/test";
import { execFile } from "node:child_process";
import { createServer } from "node:http";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";

const exec = promisify(execFile);
test("existing Binder map receives a real finding and retest, exports its accepted proposal and isolates evidence", async ({ page, browser }, info) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  const dir = mkdtempSync(path.join(tmpdir(), "builder-browser-"));
  let fixed = false;
  const server = createServer((req, res) => { res.writeHead(req.url === "/restricted" && fixed ? 403 : 200); res.end(); });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const port = (server.address() as { port: number }).port;
  try {
    await page.goto("/builder");
    await expect(page.getByText("No pipeline connection observations yet", {exact:true})).toBeVisible();
    await expect(page.locator(".brand")).toHaveText("OSCAL binder");
    await expect(page).toHaveURL(/planning\?view=connections/);
    await page.getByLabel("System name").fill("Independent access service");
    const created = page.waitForResponse(r => r.url().endsWith("/api/builder") && r.request().method() === "POST");
    await page.getByRole("button", { name: "Create pipeline connection" }).click();
    const body = await (await created).json();
    await expect(page.getByText("No observations from this connection yet. They appear after the first CI upload. No security coverage is inferred.")).toBeVisible();
    const id = body.connection.id, endpoint = `${new URL(page.url()).origin}/api/builder/connections/${id}/events`;
    await expect(page.locator("details[open] > summary").filter({hasText:"Set up the first access check"})).toBeVisible();
    await page.getByLabel("Required endpoint (expects 200)").fill(`http://127.0.0.1:${port}/required`);
    await page.getByLabel("Prohibited endpoint (expects 403)").fill(`http://127.0.0.1:${port}/restricted`);
    const downloaded = page.waitForEvent("download");
    await page.getByRole("button", { name: "Download check configuration" }).click();
    const configPath = path.join(dir, "config.json"); await (await downloaded).saveAs(configPath);
    const eventPath = path.join(dir, "event.json");
    const collectorArgs = ["public/builder-evidence.mjs", "check-access", "--config", configPath, "--revision", "before-fix", "--run-id", "run-1", "--out", eventPath];
    await expect(exec(process.execPath, collectorArgs)).rejects.toMatchObject({ code: 2 });
    await exec(process.execPath, ["public/builder-evidence.mjs", "publish", "--file", eventPath, "--endpoint", endpoint], { env: { ...process.env, AEGIS_BUILDER_TOKEN: body.token } });
    await page.getByRole("button", { name: "Dismiss credential" }).click();
    await page.getByRole("button", { name: "Refresh evidence" }).click();
    await page.getByRole("button", {name:"Open package map",exact:true}).click();
    await expect(page.getByTestId("rollup-map-workspace")).toBeVisible();
    await page.locator('[data-control-id="AC-6"]').first().click();
    await expect(page.getByTestId("pipeline-control-panel")).toContainText("Check reported FAIL");
    await navigateWorkspace(page, "release");
    await expect(page.getByTestId("release-dashboard")).toContainText("Independent access service");
    await page.getByRole("button", { name: "Open proposed plan AC-6" }).click();
    await expect(page.getByTestId("plan-proposal")).toContainText("Proposed · not accepted");
    await expect(page.getByTestId("plan-proposal")).toContainText("Not attached");
    await page.getByRole("button", { name: "Close proposed plan" }).click();
    fixed = true;
    collectorArgs[collectorArgs.indexOf("before-fix")] = "after-fix";
    collectorArgs[collectorArgs.indexOf("run-1")] = "run-2";
    await exec(process.execPath, collectorArgs);
    const published = await exec(process.execPath, ["public/builder-evidence.mjs", "publish", "--file", eventPath, "--endpoint", endpoint], { env: { ...process.env, AEGIS_BUILDER_TOKEN: body.token } });
    const receipt = JSON.parse(published.stdout);
    await page.reload();
    await expect(page.getByTestId("workspace-navigation")).toHaveAttribute("data-current-view", "release");
    await expect(page.getByTestId("release-dashboard")).toContainText("Artifact digests checked");
    await expect(page.getByTestId("release-dashboard")).not.toContainText("pods ready");
    await page.getByRole("button", { name: "Open proposed plan AC-6" }).click();
    const proposal = page.getByTestId("plan-proposal");
    await expect(proposal).toContainText("Closure proposed");
    await expect(proposal).toContainText("Reported pass");
    await expect(proposal.getByRole("button", { name: "Confirm closure", exact: true })).toBeDisabled();
    await proposal.getByRole("button", { name: "Accept proposed draft" }).click();
    const poamDownload = page.waitForEvent("download", { timeout: 20_000 });
    const poamResponse = page.waitForResponse(r => r.url().includes("/api/remediation/oscal"));
    await proposal.getByRole("button", { name: "Download OSCAL plan of action" }).click();
    const downloadResponse = await poamResponse;
    expect(downloadResponse.status(), downloadResponse.ok() ? "" : await downloadResponse.text()).toBe(200);
    const poamPath = path.join(dir, "poam.json"); await (await poamDownload).saveAs(poamPath);
    const poam = JSON.parse(readFileSync(poamPath, "utf8"))["plan-of-action-and-milestones"];
    expect(poam.risks[0].status).toBe("open");
    expect(JSON.stringify(poam)).toContain("AC-6");
    expect(JSON.stringify(poam)).not.toContain("Podinfo");
    await page.getByRole("button", { name: "Close proposed plan" }).click();
    const bundleDownload = page.waitForEvent("download");
    await page.getByRole("link", { name: "Download retained bundle" }).click();
    const bundlePath = path.join(dir, "bundle.json"); await (await bundleDownload).saveAs(bundlePath);
    const verified = await exec(process.execPath, ["public/builder-evidence.mjs", "verify", "--file", bundlePath, "--expected-id", receipt.evidenceId]);
    expect(JSON.parse(verified.stdout).integrity).toBe("verified");
    const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
    writeFileSync(bundlePath, JSON.stringify({ ...bundle, rawEvent: bundle.rawEvent + " " }));
    await expect(exec(process.execPath, ["public/builder-evidence.mjs", "verify", "--file", bundlePath, "--expected-id", receipt.evidenceId])).rejects.toMatchObject({ code: 1 });
    const other = await browser.newContext();
    const outsider = await other.request.get(`/api/builder/evidence/${receipt.evidenceId}?connection=${id}`);
    expect(outsider.status()).toBe(404);
    await other.close();
    await page.screenshot({ path: info.outputPath("builder-evidence.png"), fullPage: true });
    await navigateWorkspace(page, "connections");
    await page.getByRole("button", { name: /More actions for/ }).click();
    await page.getByRole("button", { name: "Revoke upload credential" }).click();
    await expect(page.getByRole("button", { name: "Upload credential revoked" })).toBeDisabled();
    const rejected = await page.request.post(endpoint, { headers: { authorization: `Bearer ${body.token}` }, data: readFileSync(eventPath, "utf8") });
    expect(rejected.status()).toBe(401);
    expect(errors).toEqual([]);
  } finally { await new Promise<void>(resolve => server.close(() => resolve())); rmSync(dir, { recursive: true, force: true }); }
});
