import { chooseStartingPoint, navigateWorkspace } from "./helpers/navigation";
import { expect, test, type Page } from "@playwright/test";
import { readFileSync } from "node:fs";
import { validateAssessmentResults } from "../lib/aegis/assessment-results";
import { resolveContextDocument, validateContextDocument } from "../lib/aegis/assessment-context";
import { seedReceivedRetest } from "./receiver-seed";
import { loadSampleAssessment } from "./sample-assessment";

async function openIdentityReview(page: Page) {
  await seedReceivedRetest(page);
  await page.goto("/planning/pipeline");
  await page.getByLabel("Evidence system").selectOption("example");await navigateWorkspace(page,"map");
  await chooseStartingPoint(page, "Load planning example");
  await expect(page.getByTestId("package-map")).toBeVisible();
  await expect(page.getByRole("button", { name: "New package", exact: true })).toBeVisible();
  await expect(page.getByTestId("workspace-navigation")).toHaveAttribute("data-current-view", "map");
  await navigateWorkspace(page, "release");
  await page.getByRole("button", { name: "View open security review items" }).click();
  await page.getByRole("button", { name: "Assess review item 1", exact: true }).click();
  await expect(page.getByTestId("assessment-drawer")).toBeVisible();
}

test("UID/GID planning path downloads a schema-valid open assessment results file", async ({ page }, testInfo) => {
  await openIdentityReview(page);
  await loadSampleAssessment(page);
  await page.getByRole("button", { name: "Prepare draft POA&M", exact: false }).click();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByTestId("remediation-workspace")).toBeVisible();
  await page.getByRole("button", { name: "Apply received retest", exact: true }).click();
  await expect(page.getByLabel("Corrective action", { exact: true })).toHaveValue(/10001/);
  await page.getByRole("button", { name: "Assessment results", exact: true }).click();
  const dialog = page.getByTestId("assessment-results");
  await expect(dialog).toContainText("KSV-0020");
  await expect(dialog).toContainText("Examine");
  await expect(dialog).toContainText("CM-6");
  await expect(dialog).toContainText("Configuration rescan no longer reports KSV-0020 or KSV-0021");
  await expect(dialog).toContainText("Actual application process UID and GID match the corrected manifest");
  await expect(dialog).toContainText("Corrected workload remains ready and /healthz succeeds");
  await expect(dialog).toContainText("2894050908");
  await expect(dialog).toContainText("2908682168");
  await expect(dialog).toContainText("Open");
  await expect(dialog).not.toContainText("binder.remediation-draft.v1");
  await page.screenshot({ path: testInfo.outputPath("assessment-results.png") });
  const downloading = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download OSCAL assessment results", exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe("assessment-results.json");
  const file = await download.path();
  expect(file).not.toBeNull();
  const document = JSON.parse(readFileSync(file!, "utf8"));
  expect(validateAssessmentResults(document)).toEqual({ ok: true });
  const result = document["assessment-results"].results[0];
  expect(result.findings).toHaveLength(1);
  expect(result.findings[0].description).toContain("KSV-0020");
  expect(result.findings[0].description).toContain("KSV-0021");
  expect(result.findings[0].description).toMatch(/UID/);
  expect(result.findings[0].description).toMatch(/GID/);
  const reviewed = result["reviewed-controls"]["control-selections"][0]["include-controls"].map((item: { "control-id": string }) => item["control-id"]);
  expect(reviewed).toHaveLength(323);
  expect(reviewed).toContain("cm-6");
  expect(reviewed).toContain("ac-1");
  const cm6 = result.observations.find((item: { props?: { name: string; value: string }[] }) => item.props?.some((prop) => prop.name === "control-id" && prop.value === "CM-6"));
  expect(cm6.methods).toContain("EXAMINE");
  expect(cm6.methods).toContain("TEST");
  const body=document["assessment-results"];
  const ap=resolveContextDocument(body,body["import-ap"].href,"assessment-plan");
  expect(validateContextDocument(ap,"assessment-plan")).toEqual([]);
  const objective=ap["assessment-plan"]["local-definitions"]["objectives-and-methods"].find((o:{"control-id":string})=>o["control-id"]==="cm-6").parts.find((p:{name:string})=>p.name==="assessment-objective");
  expect(result.findings[0].target["target-id"]).toBe(objective.id);
  expect(result.findings[0].target["target-id"]).not.toBe("CM-6");
  const evidence = JSON.stringify(cm6["relevant-evidence"]);
  expect(evidence).toContain("Configuration rescan no longer reports KSV-0020 or KSV-0021");
  expect(evidence).toContain("Actual application process UID and GID match the corrected manifest");
  expect(evidence).toContain("Corrected workload remains ready and /healthz succeeds");
  expect(JSON.stringify(result)).toContain("2894050908");
  expect(JSON.stringify(result)).toContain("2908682168");
  expect(result.risks[0].status).toBe("open");
  expect(JSON.stringify(document)).not.toContain('"closed"');
  expect(JSON.stringify(document)).not.toContain("agency-system-id");
  expect(JSON.stringify(document)).not.toContain("binder.remediation-draft.v1");
  expect(JSON.stringify(document)).toContain('"base64"');
  const sspDownloading=page.waitForEvent("download");
  await dialog.getByRole("button",{name:"Download OSCAL system security plan",exact:true}).click();
  const sspDownload=await sspDownloading;
  const sspFile=await sspDownload.path();
  expect(sspFile).not.toBeNull();
  const downloadedSsp=JSON.parse(readFileSync(sspFile!,"utf8"));
  expect(validateContextDocument(downloadedSsp,"system-security-plan")).toEqual([]);
  expect(downloadedSsp["system-security-plan"]["control-implementation"]["implemented-requirements"]).toHaveLength(323);
  const referencedSsp=resolveContextDocument(ap["assessment-plan"],ap["assessment-plan"]["import-ssp"].href,"system-security-plan");
  expect(downloadedSsp["system-security-plan"]["system-implementation"].components[0].uuid).toBe(referencedSsp["system-security-plan"]["system-implementation"].components[0].uuid);
  await dialog.getByRole("button", { name: "Close assessment results", exact: true }).click();
  await expect(page.getByTestId("remediation-workspace")).toBeVisible();
});
