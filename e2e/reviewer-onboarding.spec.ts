import {CCM_EXAMPLE} from "../lib/aegis/pipeline-evidence";
import {referenceAuthorizationPlan,referencePlanCount} from "./helpers/collector-reference";
import { navigateWorkspace } from "./helpers/navigation";
import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("fresh reviewer opts into actual captured evidence and exports a reviewed plan without GitHub or another browser's cookies", async ({ page, browser }, info) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("/planning");
  await expect(page.getByRole("heading", { name: "No system connected" })).toBeVisible();
  await expect(page.getByLabel("Evidence system")).toHaveValue("");
  await expect(page.getByTestId("rollup-map-workspace")).toHaveCount(1);await expect(page.getByTestId("package-map")).toHaveAttribute("data-layout-engine","round21");await expect(page.locator("[data-control-id]")).toHaveCount(0);
  await expect(page.getByTestId("release-dashboard")).toHaveCount(0);
  await page.getByRole("button", { name: "Connect a system or load captured evidence" }).click();
  await expect(page.getByText("No pipeline connection observations yet", {exact:true})).toBeVisible();
  await page.getByRole("button", { name: "Load captured Online Boutique evidence" }).click();
  await navigateWorkspace(page,"release");
  await expect(page.getByTestId("release-dashboard")).toContainText("Online Boutique · captured reference");
  const summary = await (await page.request.get("/api/builder")).json();
  const connection = summary.connections[0];
  const sourceCaptureReceipt=await (await page.request.get("/api/builder/reference")).json();
  expect(connection.history).toHaveLength(sourceCaptureReceipt.events.length);
  const measured=connection.history.filter((h:any)=>h.subject.kind==="identity");expect(measured).toHaveLength(2);
  expect(connection.history.every((h: { authentication: string }) => h.authentication === "browser-owner")).toBe(true);
  expect(measured.map((h: { run: { observedAt: string } }) => h.run.observedAt).sort()).toEqual(["2026-10-06T02:54:20.612Z", "2026-10-06T02:54:20.862Z"]);
  await page.getByRole("button", { name: referenceAuthorizationPlan }).click();
  const proposal = page.getByTestId("plan-proposal");
  await expect(proposal).toContainText("The Online Boutique frontend service account has no get permission for Secrets in this namespace.");
  await expect(proposal.getByRole("button", { name: "Confirm closure", exact: true })).toBeDisabled();
  const expired = Date.parse(measured[0].checks[0].validUntil) <= Date.now();
  await expect(proposal).toContainText("was authorized to get Kubernetes Secrets");
  await expect(proposal.getByLabel("Risk statement", { exact: true })).toHaveValue(/was authorized to get Kubernetes Secrets/);
  await expect(proposal).toContainText("Captured PASS");
  if (expired) await expect(proposal).toContainText("Evidence freshness: Expired");
  await proposal.getByRole("button", { name: "Accept proposed draft" }).click();
  const downloaded = page.waitForEvent("download", { timeout: 20_000 });
  const exported = page.waitForResponse(r => r.url().includes("/api/remediation/oscal"));
  await proposal.getByRole("button", { name: "Download OSCAL plan of action" }).click();
  const response = await exported;
  const planningHeaders = { "x-aegis-workspace": response.request().headers()["x-aegis-workspace"] };
  expect(response.status(), response.ok() ? "" : await response.text()).toBe(200);
  const file = JSON.parse(await readFile((await (await downloaded).path())!, "utf8"))["plan-of-action-and-milestones"];
  expect(JSON.stringify(file)).toContain("AC-6");
  expect(JSON.stringify(file)).not.toContain("Podinfo");
  expect(file.risks[0].status).toBe("open");
  expect(file.risks[0].description).toContain("was authorized to get Kubernetes Secrets");
  const beforeId = "bf083e020e937ee482a3f70863bc6cc31a22f63de4ee9f42e9a40d290069af3a";
  const afterId = "7c78c4bb75b2749aecd63d09c90c886ea2cbaaca7a4c19c0a92154c38b97406a";
  const finding = file.observations.find((o: { types?: string[] }) => o.types?.includes("finding"));
  expect(finding.collected).toBe("2026-10-06T02:54:20.612Z");
  const originalEvidence = finding["relevant-evidence"].filter((e: { description: string }) => e.description.startsWith("Original finding evidence:"));
  expect(originalEvidence).toHaveLength(3);
  expect(originalEvidence.every((e: { href: string }) => e.href.includes(beforeId))).toBe(true);
  const retestEvidence = finding["relevant-evidence"].filter((e: { props?: { name: string }[] }) => e.props?.some(p => p.name === "verification-check"));
  expect(retestEvidence).toHaveLength(1);
  expect(retestEvidence[0].href).toContain(afterId);
  await page.getByRole("button", { name: "Close proposed plan" }).click();
  // Simulate an acceptance retained from 6633a7c; neither UI nor server may reuse its reversed risk.
  const key = `binder.plan-proposals.v1:binder-connection:${connection.id}`;
  const saved = (await (await page.request.get(`/api/remediation?key=${encodeURIComponent(key)}`, { headers: planningHeaders })).json()).record;
  expect(saved.proposals).toHaveLength(1);
  saved.proposals[0].finding = "Reported failure: The Online Boutique frontend service account has no get permission for Secrets in this namespace.";
  saved.proposals[0].riskStatement = "Incorrect earlier saved good-state risk";
  expect((await page.request.put("/api/remediation", { headers: planningHeaders, data: saved })).status()).toBe(200);
  const blocked = await page.request.get(`/api/remediation/oscal?proposal=${encodeURIComponent(saved.proposals[0].id)}`, { headers: planningHeaders });
  expect(blocked.status()).toBe(409);
  await page.reload();
  await navigateWorkspace(page, "release");
  await page.getByRole("button", { name: referenceAuthorizationPlan }).click();
  const corrected = page.getByTestId("plan-proposal");
  await expect(corrected).toContainText("earlier acceptance does not apply");
  await expect(corrected.getByLabel("Risk statement", { exact: true })).toHaveValue(/was authorized to get Kubernetes Secrets/);
  await corrected.getByRole("button", { name: "Accept proposed draft" }).click();
  await page.getByRole("button", { name: "Close proposed plan" }).click();
  await page.reload();
  await navigateWorkspace(page, "connections");
  await expect(page.getByLabel("Import collector event JSON")).toBeVisible();
  const capture = await (await page.request.get("/api/builder/reference")).json();
  const received = page.waitForResponse(r => r.url().endsWith("/imports") && r.request().method() === "POST");
  await page.getByLabel("Import collector event JSON").setInputFiles({ name: "actual-observation.json", mimeType: "application/json", buffer: Buffer.from(capture.events[0].rawEvent) });
  expect((await received).status()).toBe(201);
  expect((await (await page.request.get("/api/builder")).json()).connections[0].history).toHaveLength(capture.events.length);
  const other = await browser.newContext();
  const otherPage = await other.newPage();
  await otherPage.goto("/planning");
  await expect(otherPage.getByRole("heading", { name: "No system connected" })).toBeVisible();
  expect((await (await other.request.get("/api/builder")).json()).connections).toHaveLength(0);
  await otherPage.getByRole("button", { name: "Connect a system or load captured evidence" }).click();
  await otherPage.getByRole("button", { name: "Load captured Online Boutique evidence" }).click();
  await navigateWorkspace(otherPage, "release");
  await expect(otherPage.getByTestId("release-dashboard")).toContainText("Online Boutique · captured reference");
  const separate = await (await other.request.get("/api/builder")).json();
  expect(separate.connections[0].id).not.toBe(connection.id);
  await other.close();
  await page.getByRole("button", { name: "Open package map" }).click();
  await page.locator('[data-control-id="AC-6"]').first().click();
  await expect(page.getByTestId("pipeline-control-panel")).toContainText("was authorized to get Kubernetes Secrets");
  await page.screenshot({ path: info.outputPath("reviewer-reference-map.png"), fullPage: true });
  expect(errors).toEqual([]);
});

test("Podinfo is available only after an explicit example selection", async ({ page }) => {
  await page.goto("/planning");
  await expect(page.getByRole("heading", { name: "No system connected" })).toBeVisible();
  await page.getByText("More starting points").click();
  await page.getByRole("button", { name: "Load podinfo-gsa-evidence-0928 evidence example" }).click();
  await expect(page.getByTestId("binder-summary")).toBeVisible();
  await navigateWorkspace(page, "release");
  await expect(page.getByTestId("release-dashboard")).toContainText(new URL(CCM_EXAMPLE.pipelineUrl).pathname.split("/-/")[0].split("/").at(-1)!);
  await page.getByLabel("Evidence system").selectOption("");
  await expect(page.getByRole("heading", { name: "No evidence selected" })).toBeVisible();
  await page.reload();
  await expect(page.getByTestId("workspace-navigation")).toHaveAttribute("data-current-view", "release");
  await expect(page.getByRole("heading", { name: "No evidence selected" })).toBeVisible();
});
