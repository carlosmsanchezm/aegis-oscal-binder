import { chooseStartingPoint } from "./helpers/navigation";
import { expect, test } from "@playwright/test";

test("SC-7 evidence returns to its Level 2 statement by button and Escape", async ({ page }) => {
  await page.route("**/api/pipeline/events", route => route.fulfill({ json: { ok: true, configured: false, webhookPath: "/api/pipeline/events", receivedAt: null, evidence: null, releases: [] } }));
  await page.goto("/planning");
  await page.getByLabel("Evidence system").selectOption("example");
  const loaded = page.waitForResponse(response => response.url().endsWith("/api/demo/sa1/oscal/ingest") && response.request().method() === "POST");
  await chooseStartingPoint(page, "Load planning example");
  expect((await loaded).ok()).toBe(true);
  await expect(page.getByRole("button", { name: "Load planning example", exact: true })).toBeHidden();
  const map = page.getByTestId("package-map");
  await map.locator('[data-control-id="SC-7"]').dblclick();
  await expect(page.getByTestId("level2-item-coverage")).toContainText("Recorded");
  await expect(page.getByTestId("level2-item-coverage")).toContainText("#2894050908");
  await page.getByTestId("statement-b").click();
  const evidence = page.getByRole("button", { name: "Inspect evidence details", exact: true });
  await evidence.click();
  await expect(page.getByTestId("evidence-focus")).toBeVisible();
  await expect(page.getByTestId("evidence-focus-card")).toContainText("configuration.json");
  await expect(page.getByTestId("evidence-focus-card")).toContainText("16815627409/artifacts/file/evidence/configuration.json");
  await expect(page.getByTestId("evidence-focus")).toContainText("Evidence is linked to the control, not to statement items.");
  await expect(page.getByTestId("evidence-focus").locator("[data-item-id]")).toHaveCount(0);
  await expect.poll(async () => page.getByTestId("evidence-focus").evaluate(el => el.getBoundingClientRect().width)).toBeGreaterThan(1200);
  await expect.poll(async () => page.getByTestId("evidence-focus-card").evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.getByRole("button", { name: /← SC-7 · Level 2/ }).click();
  await expect(page.getByTestId("level2-focus")).toBeVisible();
  await expect(page.getByTestId("level2-breadcrumb")).toContainText("SC-7");
  await expect(page.getByTestId("statement-b")).toHaveAttribute("aria-pressed", "true");
  await evidence.click();
  await page.keyboard.press("Escape");
  await expect(page.getByTestId("level2-focus")).toBeVisible();
  await expect(page.getByTestId("statement-b")).toHaveAttribute("aria-pressed", "true");
  await page.getByTestId("level2-back").click();
  await page.getByRole("button", { name: "Close panel" }).click();
  await page.locator('summary[aria-label="Release snapshot #2894050908"]').click();
  await page.getByRole("option", { name: /None current map/ }).click();
  await expect(page.locator('summary[aria-label="Release snapshot None"]')).toBeVisible();
  await map.getByRole("button", { name: /EV-SC8-01/ }).first().dblclick();
  await expect(page.getByTestId("evidence-focus")).toBeVisible();
  await page.getByRole("button", { name: "← Map Esc" }).click();
  await expect(page.getByTestId("evidence-focus")).toHaveCount(0);
  await expect(page.getByTestId("evidence-card")).toBeVisible();
});
