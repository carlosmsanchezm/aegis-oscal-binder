import { chooseStartingPoint, navigateWorkspace } from "./helpers/navigation";
import { test, expect } from "@playwright/test";
import { receivedRetest } from "../test/support/received-retest";

test("round 21e family map retains latest control sources and the control-level focus", async ({ page }) => {
  const evidence = receivedRetest();
  await page.route("**/api/pipeline/events", route => route.fulfill({ json: { ok: true, configured: false, webhookPath: "/api/pipeline/events", receivedAt: evidence.createdAt, evidence, releases: [{ evidence, receivedAt: evidence.createdAt }] } }));
  await page.goto("/planning/pipeline");
  await page.getByLabel("Evidence system").selectOption("pipeline");
  await chooseStartingPoint(page, "Load planning example");
  await expect(page.getByTestId("map-stage")).toBeVisible();
  await page.getByRole("checkbox", {name:"Show untouched controls"}).uncheck();
  await expect(page.locator("[data-control-id]")).toHaveCount(27);
  await expect(page.locator('[data-control-id][data-release-linked="true"]')).toHaveCount(15);
  const unlinkedProposals = await page.locator('[data-control-id]:not([data-release-linked="true"])').evaluateAll(nodes => nodes.map(node => ({proposals:Number(node.getAttribute("data-proposed")),recorded:node.getAttribute("data-rollup")==="recorded"})));
  expect(unlinkedProposals).toHaveLength(12);
  expect(unlinkedProposals.every(control => control.recorded || control.proposals > 0)).toBe(true);
  await page.getByRole("checkbox", {name:"Show untouched controls"}).check();
  await expect(page.locator("[data-family-box]")).toHaveCount(18);
  await expect(page.locator("[data-control-id]")).toHaveCount(323);
  await expect(page.locator('[data-control-id][data-rollup="recorded"]')).toHaveCount(15);
  await expect(page.locator('[data-family-box="AT"]')).toHaveAttribute("data-linked", "0");
  await expect(page.locator('[data-control-id="AT-1"]')).toHaveCount(1);
  await expect(page.getByTestId("map-rollup-summary")).toContainText("15 linked");
  await expect(page.getByTestId("map-rollup-summary")).toContainText("308 blank");
  await expect(page.locator('[data-family-header="CM"]')).toContainText("2 linked");
  await expect(page.locator('[data-family-header="CM"] .pmap-within')).toHaveAttribute("title", /Moderate/);
  await expect(page.locator('[data-family-header="CM"] .pmap-within > span').first()).toHaveAttribute("title", /25 blank/);
  const cm6 = page.locator('[data-control-id="CM-6"]');
  await cm6.click();
  const panel = page.getByTestId("pipeline-control-panel");
  await expect(panel).toContainText("#2908682168");
  await expect(panel.locator(".pipeline-control-artifact a[data-source-href]")).toHaveAttribute("data-source-href", /16910084348.*configuration.json$/);
  await expect(panel.locator(".pipeline-control-checks li")).toHaveCount(3);
  await expect(panel).toContainText("KSV-0125");
  await panel.getByText(/Separate finding · Application UID\/GID/).click();
  await panel.locator("details.panel-block[open] .control-retest > summary").click();
  await expect(panel.locator("details.panel-block[open] .pipeline-control-checks li").first()).toBeVisible();
  await expect(panel).toContainText("A pass does not resolve another finding");
  await expect(panel.locator("textarea,input,form")).toHaveCount(0);
  await expect(panel).not.toContainText("SSP evidence");
  await cm6.dblclick();
  await expect(page.getByTestId("level2-focus")).toBeVisible();
  await expect(page.getByTestId("level2-links")).toContainText("RA-5");
  await expect(page.getByTestId("level2-links")).toContainText("AU-2");
  await expect(page.getByTestId("level2-evidence")).toHaveCount(0);
  await page.getByTestId("level2-back").click();
  await expect(page.locator("[data-family-box]")).toHaveCount(18);
  await page.getByRole("button", { name: "Close panel", exact: true }).click();
  await page.locator('[data-control-id="AC-6"]').click();
  await expect(panel).toContainText("#2894050908");
  await expect(panel.locator(".pipeline-control-artifact a[data-source-href]").first()).toHaveAttribute("data-source-href", /16815627409/);
  await navigateWorkspace(page, "release");
  await expect(page.locator(".baseline-footprint-grid > button")).toHaveCount(18);
  await expect(page.locator("[data-family-box]")).toHaveCount(0);
  await page.getByRole("button", { name: /linked · Baseline coverage/ }).click();
  await expect(page.locator("[data-family-box]")).toHaveCount(18);
  await page.locator('[data-control-id="CM-6"]').click();
  await expect(panel).toContainText("#2908682168");
  await page.locator('summary[aria-label="Release snapshot #2908682168"]').click();
  await page.getByRole("option", { name: /None current map/ }).click();
  await expect(page.locator('summary[aria-label="Release snapshot None"]')).toBeVisible();
  await expect(page.locator("[data-control-id]")).toHaveCount(323);
});
