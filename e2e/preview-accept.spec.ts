import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("unconfigured preview accepts CM-6 in this tab, reloads, and exports an open risk", async ({ page, context }, testInfo) => {
  await page.goto("/planning/pipeline");
  await page.getByLabel("Evidence system").selectOption("example");
  const selector = page.getByLabel("Release selection", { exact: true });
  await expect(selector.locator("option:checked")).toContainText("#2894050908");
  await expect(selector).toContainText("#2908682168");
  const proposals = page.getByTestId("proposed-plans");
  await expect(proposals).toContainText("CM-6");
  await page.getByLabel("Release inspector").getByRole("button", {name:/^Effort/}).click();
  await page.getByRole("complementary", { name: "Recommended next efforts" }).getByRole("button", { name: "Open plan for CM-6 · Application UID/GID hardening", exact: true }).click();
  const drawer = page.getByTestId("plan-proposal");
  await expect(drawer).toContainText("Original failed observation #2894050908");
  await expect(drawer).toContainText("Retest #2908682168");
  await expect(drawer.locator("ol li small").filter({ hasText: "PASS" })).toHaveCount(3);
  await expect(drawer.getByRole("button", { name: "Confirm closure", exact: true })).toBeDisabled();
  await drawer.getByRole("button", { name: "Accept proposed draft" }).click();
  await expect(drawer).toContainText("Accepted · ready to close · needs a person");
  await expect(drawer).toContainText("Kept in this browser tab");
  await expect(drawer.getByRole("button", { name: "Confirm closure", exact: true })).toBeEnabled();
  await page.reload();
  await proposals.getByRole("button", { name: "Open proposed plan CM-6 · Application UID/GID hardening", exact: true }).click();
  await expect(drawer).toContainText("Accepted · ready to close · needs a person");
  await expect(drawer.getByRole("button", { name: "Confirm closure", exact: true })).toBeEnabled();
  const downloaded = page.waitForEvent("download");
  await drawer.getByRole("button", { name: "Download OSCAL plan of action" }).click();
  const file = JSON.parse(await readFile((await (await downloaded).path())!, "utf8"))["plan-of-action-and-milestones"];
  expect(file.risks[0].status).toBe("open");
  expect(file["poam-items"][0].props.some((p: { name: string; value: string }) => p.name === "poam-id" && p.value)).toBe(false);
  expect(file["system-id"]["identifier-type"]).toBe("urn:aegis:system-id:internal");
  await expect(drawer.getByRole("alert")).toHaveCount(0);
  const key = "binder.plan-proposals.v1:https://gitlab.com/enbuild-staging/enbuild-deployments/podinfo-gsa-evidence-0928";
  const standard = await context.request.get(`/api/remediation?key=${encodeURIComponent(key)}`);
  expect((await standard.json()).record).toBeNull();
  expect((await context.cookies()).some((cookie) => cookie.name === "aegis_sa1_sid")).toBe(true);
  const shot = process.env.AEGIS_SCREENSHOT ?? testInfo.outputPath("preview-accept.png");
  await page.screenshot({ path: shot, fullPage: true });
});
